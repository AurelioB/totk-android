"""The pre-game menu's settings model (android/java/.../setup/Settings.java) on a host JVM: the settings.env text the
runtime reads at game start, preset matching and application, the option rules and the per-device recommendation.
"""
from pathlib import Path
import shutil
import subprocess
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[1]
TOTK = ROOT / 'games/totk'
SOURCE = TOTK / 'android/java/com/aure/totk/setup/Settings.java'
PROBE = TOTK / 'tests/settings/SettingsProbe.java'
# Every key the native side accepts from settings.env (runtime/frontend_android.c allowlist, contract table).
ALLOWED = {'TOTK_FPS60', 'TOTK_GPU_TIME', 'TOTK_FRAMEGEN', 'TOTK_REALTIME', 'TOTK_FRAME_LAG', 'TOTK_FPS_AUTO', 'DM_PRESENT_HZ',
           'DM_PRESENT_INTERVAL', 'TOTK_PRESENT_SLOTS', 'TOTK_VK_PRESENT', 'TOTK_ACQUIRE_SLACK', 'TOTK_ACQUIRE_CLOCK',
           'TOTK_PACE', 'TOTK_ASYNC_REPLAY', 'TOTK_RENDER_RES', 'TOTK_POST_SCALE', 'TOTK_POST_SHARPNESS',
           'TOTK_POST_SGSR_SHARPNESS', 'TOTK_FXAA', 'TOTK_POST_AA', 'TOTK_SHADOW_RES', 'TOTK_OPERATION_MODE',
           'TOTK_NATIVE_UI', 'TOTK_OVERLAY', 'TOTK_OVERLAY_POS', 'TOTK_COMPANION', 'TOTK_FACE_BUTTONS',
           'TOTK_AUDIO_PREFILL_MS', 'TOTK_LOCALE', 'TOTK_LANG', 'TOTK_DATA_DIR', 'TOTK_RUMBLE', 'TOTK_RUMBLE_GAIN', 'TOTK_GYRO',
           'TOTK_AUTOLOAD'}
FRONTEND = TOTK / 'runtime/frontend_android.c'
FRAMEGEN = ['TOTK_FPS60=0', 'TOTK_FRAMEGEN=locked', 'TOTK_REALTIME=1', 'TOTK_FRAME_LAG=0', 'TOTK_FPS_AUTO=0', 'DM_PRESENT_HZ=60',
            'DM_PRESENT_INTERVAL=game', 'TOTK_PRESENT_SLOTS=1', 'TOTK_VK_PRESENT=ahb', 'TOTK_ACQUIRE_SLACK=0',
            'TOTK_ACQUIRE_CLOCK=0', 'TOTK_PACE=0', 'TOTK_ASYNC_REPLAY=0']


class SettingsTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        javac, java = shutil.which('javac'), shutil.which('java')
        if not javac or not java:
            raise unittest.SkipTest('javac/java not found')
        cls.java = java
        cls.temp = tempfile.TemporaryDirectory(prefix='totk-settings-')
        cls.classes = Path(cls.temp.name)
        subprocess.run([javac, '--release', '17', '-encoding', 'UTF-8', '-d', str(cls.classes), str(SOURCE), str(PROBE)],
                       check=True, capture_output=True, text=True)

    @classmethod
    def tearDownClass(cls):
        cls.temp.cleanup()

    def run_probe(self, *commands):
        result = subprocess.run([self.java, '-cp', str(self.classes), 'com.aure.totk.setup.SettingsProbe'],
                                input='\n'.join(commands) + '\n', capture_output=True, text=True, timeout=60, check=True)
        return result.stdout.splitlines()

    def values(self, line):
        return dict(pair.split('=', 1) for pair in line.split())

    def env(self, locale='en-GB', **stored):
        line = self.run_probe('env ' + locale + ''.join(f' {k}={v}' for k, v in stored.items()))[0]
        lines = line.split('|')[:-1]
        self.assertTrue(lines[0].startswith('# Generated by the TotK Native menu'), lines[0])
        body = [l for l in lines if not l.startswith('#')]
        keys = [l.split('=', 1)[0] for l in body]
        self.assertLessEqual(set(keys), ALLOWED)
        self.assertEqual(len(keys), len(set(keys)), 'a key written twice')
        return body

    def test_allowlist_matches_the_runtime(self):
        import re
        source = FRONTEND.read_text()
        block = source[source.index('settings_keys[] = {'):]
        block = block[:block.index('};')]
        self.assertEqual(set(re.findall(r'"([A-Z0-9_]+)"', block)), ALLOWED)

    def test_default_env_is_the_shipping_behaviour(self):
        self.assertEqual(self.env(), [
            'TOTK_FPS60=0', 'TOTK_ACQUIRE_SLACK=1', 'TOTK_POST_SCALE=off', 'TOTK_OPERATION_MODE=handheld', 'TOTK_NATIVE_UI=0',
            'TOTK_OVERLAY=off', 'TOTK_OVERLAY_POS=tr', 'TOTK_COMPANION=1', 'TOTK_FACE_BUTTONS=label', 'TOTK_AUDIO_PREFILL_MS=20',
            'TOTK_RUMBLE=1', 'TOTK_RUMBLE_GAIN=1.0', 'TOTK_GYRO=1', 'TOTK_LOCALE=en-GB'])

    def test_every_option_maps_as_the_contract_says(self):
        env = self.env('-', frame_rate='60', render_res='960x540', latency='smoothest', upscaler='fsr', sharpness_fsr='35',
                       aa='smaa', shadows='low', console_mode='docked', native_hud='on', overlay='full', overlay_pos='bl',
                       second_screen='off', buttons='xbox', audio_latency='safe', rumble='50', motion='off', game_language='pt-BR')
        self.assertEqual(env, [
            'TOTK_FPS60=1', 'TOTK_GPU_TIME=hardware', 'TOTK_RENDER_RES=960x540', 'TOTK_ACQUIRE_SLACK=2', 'TOTK_POST_SCALE=fsr', 'TOTK_POST_SHARPNESS=0.35',
            'TOTK_FXAA=0', 'TOTK_POST_AA=smaa', 'TOTK_SHADOW_RES=256', 'TOTK_OPERATION_MODE=docked', 'TOTK_NATIVE_UI=1',
            'TOTK_OVERLAY=full', 'TOTK_OVERLAY_POS=bl', 'TOTK_COMPANION=0', 'TOTK_FACE_BUTTONS=position',
            'TOTK_AUDIO_PREFILL_MS=40', 'TOTK_RUMBLE=1', 'TOTK_RUMBLE_GAIN=0.5', 'TOTK_GYRO=0', 'TOTK_LANG=pt-BR'])
        self.assertIn('TOTK_ACQUIRE_SLACK=0', self.env(latency='responsive'))
        self.assertFalse(any(l.startswith('TOTK_GPU_TIME') for l in self.env(frame_rate='30')))   # 30 fps: the runtime's default
        self.assertIn('TOTK_SHADOW_RES=288', self.env(shadows='medium'))
        self.assertIn('TOTK_AUDIO_PREFILL_MS=10', self.env(audio_latency='low'))
        off = self.env(aa='off')
        self.assertIn('TOTK_FXAA=0', off); self.assertNotIn('TOTK_POST_AA=smaa', off)
        self.assertIn('TOTK_OVERLAY=fps', self.env(overlay='fps'))

    def test_rumble_strength_and_motion(self):
        off = self.env(rumble='0')
        self.assertIn('TOTK_RUMBLE=0', off)
        self.assertFalse(any(l.startswith('TOTK_RUMBLE_GAIN') for l in off))   # no vibration devices for the game at all
        self.assertIn('TOTK_RUMBLE_GAIN=0.25', self.env(rumble='25'))
        self.assertIn('TOTK_RUMBLE_GAIN=0.75', self.env(rumble='75'))
        self.assertIn('TOTK_GYRO=0', self.env(motion='off'))
        self.assertIn('TOTK_RUMBLE_GAIN=1.0', self.env(rumble='33'))   # not a menu value: the default

    def test_sharpness_follows_the_selected_upscaler_only(self):
        fsr = self.env(upscaler='fsr')
        self.assertIn('TOTK_POST_SHARPNESS=0.2', fsr)
        self.assertFalse(any(l.startswith('TOTK_POST_SGSR_SHARPNESS') for l in fsr))
        sgsr = self.env(upscaler='sgsr', sharpness_fsr='90')
        self.assertIn('TOTK_POST_SCALE=sgsr', sgsr)
        self.assertIn('TOTK_POST_SGSR_SHARPNESS=2.0', sgsr)   # 50 * 0.04
        self.assertFalse(any(l.startswith('TOTK_POST_SHARPNESS') for l in sgsr))
        self.assertIn('TOTK_POST_SGSR_SHARPNESS=1.4', self.env(upscaler='sgsr', sharpness_sgsr='35'))
        self.assertIn('TOTK_POST_SHARPNESS=1.0', self.env(upscaler='fsr', sharpness_fsr='100'))
        self.assertIn('TOTK_POST_SHARPNESS=0.0', self.env(upscaler='fsr', sharpness_fsr='0'))
        self.assertFalse(any('SHARPNESS' in l for l in self.env(upscaler='off', sharpness_fsr='90')))

    def test_frame_generation_writes_the_locked_timing_block_and_no_latency(self):
        env = self.env(frame_gen='on', latency='smoothest', render_res='1152x648')
        self.assertEqual(env[:len(FRAMEGEN)], FRAMEGEN)
        self.assertEqual(sum(l.startswith('TOTK_ACQUIRE_SLACK=') for l in env), 1)
        self.assertIn('TOTK_RENDER_RES=1152x648', env)
        self.assertFalse(any(l.startswith(('DM_DETCLOCK', 'TOTK_MFX', 'TOTK_GPU_TIME')) for l in env))

    def test_language_and_locale(self):
        self.assertIn('TOTK_LOCALE=zh-Hant-TW', self.env('zh-Hant-TW'))
        self.assertIn('TOTK_LANG=ja', self.env('zh-Hant-TW', game_language='ja'))
        self.assertFalse(any(l.startswith('TOTK_LOCALE') for l in self.env('zh-Hant-TW', game_language='ja')))
        self.assertFalse(any(l.startswith('TOTK_LOCALE') for l in self.env('-')))
        self.assertFalse(any(l.startswith('TOTK_LOCALE') for l in self.env('en;rm')))   # never a malformed line

    def test_game_data_folder_on_another_volume(self):
        # Only a folder other than the primary one is written, first (the runtime reads it before choosing its data
        # folder and log); a value that could break the line format is never written.
        sd = '/storage/AAAA-AAAA/Android/data/com.aure.totk/files'
        lines = self.run_probe('envdir en-GB ' + sd, 'envdir en-GB -', 'envdir en-GB relative/path')
        on_card, primary, relative = (line.split('|')[:-1] for line in lines)
        self.assertEqual([l for l in on_card if not l.startswith('#')][0], 'TOTK_DATA_DIR=' + sd)
        self.assertFalse(any(l.startswith('TOTK_DATA_DIR') for l in primary + relative))
        self.assertEqual([l for l in on_card if not l.startswith('TOTK_DATA_DIR')], primary)

    def test_stored_values_are_validated(self):
        values = self.values(self.run_probe('stored frame_rate=45 overlay=huge sharpness_fsr=101 sharpness_sgsr=-1 '
                                            'game_language=xx unknown=1 aa=smaa')[0])
        self.assertEqual((values['frame_rate'], values['overlay'], values['sharpness_fsr'], values['sharpness_sgsr'],
                          values['game_language'], values['aa']), ('30', 'off', '20', '50', 'auto', 'smaa'))
        self.assertNotIn('unknown', values)
        self.assertEqual(self.values(self.run_probe('stored frame_rate=60 frame_gen=on')[0])['frame_rate'], '30')

    def test_option_rules(self):
        sixty, generated, back = map(self.values, self.run_probe('set frame_gen=on frame_rate=60', 'set frame_rate=60 frame_gen=on',
                                                                  'set frame_rate=60 frame_rate=30'))
        self.assertEqual((sixty['frame_rate'], sixty['frame_gen']), ('60', 'off'))
        self.assertEqual((generated['frame_rate'], generated['frame_gen']), ('30', 'on'))
        self.assertEqual(back['frame_gen'], 'off')
        up, wrap, clamp, low = map(self.values, self.run_probe('step sharpness_fsr 1', 'step overlay_pos -1 overlay_pos=tl',
                                                               'step sharpness_sgsr 1 sharpness_sgsr=100', 'step frame_rate 1'))
        self.assertEqual(up['sharpness_fsr'], '25'); self.assertEqual(wrap['overlay_pos'], 'br')
        self.assertEqual(clamp['sharpness_sgsr'], '100')
        self.assertEqual((low['frame_rate'], low['frame_gen']), ('60', 'off'))

    def test_presets_match_and_apply(self):
        light, balanced, smooth, sixty, custom, smooth_any_latency, screen_free, medium_light = self.run_probe(
            'preset render_res=960x540',
            'preset',
            'preset frame_gen=on render_res=1152x648',
            'preset frame_rate=60',
            'preset frame_rate=60 render_res=960x540',
            'preset frame_gen=on render_res=1152x648 latency=responsive',
            'preset overlay=full console_mode=docked buttons=xbox sharpness_fsr=80',
            'preset render_res=960x540 shadows=medium')
        self.assertEqual((light, balanced, smooth, sixty, custom, smooth_any_latency, screen_free, medium_light),
                         ('light', 'balanced', 'smooth', '60fps', 'custom', 'smooth', 'balanced', 'custom'))
        applied = self.values(self.run_probe('apply smooth frame_rate=60 latency=responsive overlay=full sharpness_fsr=80 upscaler=fsr')[0])
        self.assertEqual({k: applied[k] for k in ('frame_rate', 'frame_gen', 'render_res', 'upscaler', 'aa', 'shadows')},
                         {'frame_rate': '30', 'frame_gen': 'on', 'render_res': '1152x648', 'upscaler': 'off', 'aa': 'fxaa', 'shadows': 'high'})
        self.assertEqual((applied['latency'], applied['overlay'], applied['sharpness_fsr']), ('responsive', 'full', '80'))
        self.assertEqual(self.run_probe('apply custom render_res=960x540')[0].split().count('render_res=960x540'), 1)

    def profile(self, *socs):
        return [tuple(line.split(' ', 2)) for line in self.run_probe(*('profile ' + s for s in socs))]

    def test_soc_profiles(self):
        # Exact SOC_MODEL tokens: each Dragonwing part shares its Snapdragon counterpart's device-tested profile.
        elite, gen2, gen4 = ('60fps', 'true', 'Snapdragon 8 Elite class'), ('balanced', 'true', 'Snapdragon 8 Gen 2 class'), \
            ('light', 'true', 'Snapdragon 7 Gen 4 class')
        self.assertEqual(self.profile('CQ8725S', 'SM8750', 'QCS8550', 'QCM8550', 'SM8550', 'CQ7790S', 'CQ7790M', 'SM7750'),
                         [elite, elite, gen2, gen2, gen2, gen4, gen4, gen4])
        # case, blanks and a suffix after '-' or a space are tolerated
        self.assertEqual(self.profile('qcs8550', '  SM8750-AB', 'CQ7790S v2'), [gen2, elite, gen4])
        # everything else is untested: Light without the badge, SM8650 included; never a substring match
        untested = ('light', 'false', 'null')
        self.assertEqual(self.profile('SM8650', 'SM8725', 'XSM8550', 'SM85500', 'CQ8725', 'QCS8550A', 'Tensor G3', 'unknown', '-'),
                         [untested] * 9)

    def test_first_run_uses_the_profile_with_experiments_off(self):
        odin, thor, duo, unknown, none = map(self.values, self.run_probe(
            'first CQ8725S', 'first QCS8550', 'first CQ7790S', 'first SM8650', 'first'))
        experiments_off = {'frame_gen': 'off', 'upscaler': 'off', 'native_hud': 'off'}
        for values in (odin, thor, duo, unknown, none):
            self.assertEqual({k: values[k] for k in experiments_off}, experiments_off)
        self.assertEqual(self.run_probe(*('preset ' + ' '.join(f'{k}={v}' for k, v in v.items()) for v in (odin, thor, duo, unknown, none))),
                         ['60fps', 'balanced', 'light', 'light', 'light'])
        # the approved Duo profile: 540p scene, full shadows (no TOTK_SHADOW_RES), balanced latency
        self.assertEqual((duo['render_res'], duo['shadows'], duo['latency']), ('960x540', 'high', 'balanced'))
        # the device-tested Odin profile: FPS60 with hardware GPU time
        sixty = self.env(**{k: odin[k] for k in ('frame_rate', 'frame_gen', 'render_res', 'latency', 'upscaler', 'aa', 'shadows')})
        self.assertEqual(sixty[:2], ['TOTK_FPS60=1', 'TOTK_GPU_TIME=hardware'])
        self.assertFalse(any(l.startswith(('TOTK_FRAMEGEN', 'TOTK_SHADOW_RES', 'TOTK_RENDER_RES')) for l in sixty))

    def test_env_write_is_atomic_and_reports_failures(self):
        # The menu refuses to start the game silently when this write fails (Retry / Start anyway), so failures must
        # surface as an exception with a reason and must never leave a partial file or a stray temp file behind.
        with tempfile.TemporaryDirectory() as temp:
            d = Path(temp)
            self.assertEqual(self.run_probe(f'write {d} settings.env A=1'), ['ok'])
            self.assertEqual((d / 'settings.env').read_text(), 'A=1')
            self.assertEqual(sorted(p.name for p in d.iterdir()), ['settings.env'])
            self.assertEqual(self.run_probe(f'write {d} settings.env B=2'), ['ok'])
            self.assertEqual((d / 'settings.env').read_text(), 'B=2')
            # temp file cannot be created (a directory is in its place): the old file stays as it was
            (d / 'settings.env.tmp').mkdir()
            answer = self.run_probe(f'write {d} settings.env C=3')[0]
            self.assertTrue(answer.startswith('error '), answer)
            self.assertEqual((d / 'settings.env').read_text(), 'B=2')
            self.assertFalse((d / 'settings.env.tmp').exists())   # the failed temp path is cleaned up too
            # rename fails (the target is a non-empty directory): the temp file is removed again
            (d / 'blocked').mkdir(); (d / 'blocked' / 'x').write_text('x')
            answer = self.run_probe(f'write {d} blocked C=3')[0]
            self.assertTrue(answer.startswith('error '), answer)
            self.assertFalse((d / 'blocked.tmp').exists())
            # the folder itself is missing
            answer = self.run_probe(f'write {d / "missing"} settings.env C=3')[0]
            self.assertTrue(answer.startswith('error '), answer)
            self.assertFalse((d / 'missing').exists())

    def test_tab_defaults(self):
        perf, screen = map(self.values, self.run_probe(
            'defaults performance CQ7790S frame_gen=on render_res=game overlay=full shadows=low',
            'defaults screen CQ7790S overlay=full console_mode=docked frame_rate=60'))
        self.assertEqual((perf['frame_gen'], perf['render_res'], perf['overlay'], perf['shadows']), ('off', '960x540', 'full', 'low'))
        self.assertEqual((screen['overlay'], screen['console_mode'], screen['frame_rate']), ('off', 'handheld', '60'))
        picture = self.values(self.run_probe('defaults picture QCS8550 upscaler=sgsr sharpness_sgsr=80 shadows=low render_res=960x540')[0])
        self.assertEqual((picture['upscaler'], picture['sharpness_sgsr'], picture['shadows'], picture['render_res']),
                         ('off', '50', 'high', '960x540'))
        odin, unknown = map(self.values, self.run_probe('defaults performance CQ8725S frame_gen=on', 'defaults performance SM8650 frame_rate=60'))
        self.assertEqual((odin['frame_rate'], odin['frame_gen']), ('60', 'off'))
        self.assertEqual((unknown['frame_rate'], unknown['render_res']), ('30', '960x540'))


if __name__ == '__main__':
    unittest.main()
