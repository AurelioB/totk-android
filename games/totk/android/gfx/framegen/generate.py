#!/usr/bin/env python3
"""Regenerate embedded Vulkan 1.3 framegen shaders without a game/Android build.

No network, device, or repository build directory is involved. Supply --compiler
for an NDK glslc or glslangValidator when neither is on PATH.
"""
import argparse
from pathlib import Path
import shutil
import struct
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parent


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--compiler", help="Path to glslc or glslangValidator")
    parser.add_argument("--scratch", type=Path, help="Parent for temporary SPIR-V artifacts")
    parser.add_argument("--production-only", action="store_true",
                        help="Regenerate production headers, leaving host fixture shaders untouched")
    parser.add_argument("--qcom-only", action="store_true",
                        help="Regenerate only vk_framegen_qcom_spv.h; preserve existing engine bytecode")
    args = parser.parse_args()
    compiler = args.compiler or shutil.which("glslc") or shutil.which("glslangValidator")
    if not compiler:
        parser.error("glslc/glslangValidator not found; supply --compiler")
    compiler = str(Path(compiler).resolve())
    glslang = "glslang" in Path(compiler).name.lower()
    if args.scratch:
        args.scratch.mkdir(parents=True, exist_ok=True)
    header = ("/* Generated by framegen/generate.py; do not edit.\n"
              " * Vulkan 1.3; no shader compilation occurs on device.\n */\n"
              "#pragma once\n#include <stdint.h>\n\n")
    results = {"vk_framegen_spv.h": [header], "vk_framegen_qcom_spv.h": [header]}
    shaders = [("framegen", stage, "vk_framegen_spv.h") for stage in ("vert", "frag")]
    shaders.append(("framegen_interp", "frag", "vk_framegen_spv.h"))
    shaders.append(("framegen_authority", "comp", "vk_framegen_spv.h"))
    shaders.append(("framegen_writer", "comp", "vk_framegen_spv.h"))
    shaders.append(("framegen_qcom", "frag", "vk_framegen_qcom_spv.h"))
    if not args.production_only:
        results["vk_framegen_test_spv.h"] = [header]
        shaders += [(name, stage, "vk_framegen_test_spv.h")
                    for name in ("test_ui", "test_transfer") for stage in ("vert", "frag")]
        shaders.append(("test_depth", "frag", "vk_framegen_test_spv.h"))
    if args.qcom_only:
        results = {"vk_framegen_qcom_spv.h": [header]}
        shaders = [("framegen_qcom", "frag", "vk_framegen_qcom_spv.h")]
    with tempfile.TemporaryDirectory(prefix="framegen-shaders-", dir=args.scratch) as work:
        for name, stage, destination in shaders:
            source = ROOT / f"{name}.{stage}"
            output = Path(work) / f"{name}.{stage}.spv"
            command = ([compiler, "-V", "--target-env", "vulkan1.3"] if glslang else
                       [compiler, "--target-env=vulkan1.3", "-O"])
            subprocess.run(command + [str(source), "-o", str(output)], check=True)
            data = output.read_bytes()
            if len(data) % 4:
                raise ValueError(f"SPIR-V is not word aligned: {source}")
            words = struct.unpack(f"<{len(data) // 4}I", data)
            result = results[destination]
            result.append(f"static const uint32_t {name}_{stage}_spv[] = {{\n")
            for start in range(0, len(words), 8):
                result.append("    " + ", ".join(f"0x{word:08x}" for word in words[start:start + 8]) + ",\n")
            result.append("};\n\n")
            print(f"{name}_{stage}_spv: {len(data)} bytes")
    for destination, result in results.items():
        (ROOT.parent / destination).write_text("".join(result))


if __name__ == "__main__":
    main()
