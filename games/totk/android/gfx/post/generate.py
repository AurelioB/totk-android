#!/usr/bin/env python3
"""Regenerate the embedded Vulkan 1.3 post shaders and original SMAA LUT bytes.

No network, Android build, device, or repository build directory is involved.
Use --compiler for an NDK glslc or a glslangValidator (including the local shim).
"""

import argparse
from pathlib import Path
import re
import shutil
import struct
import subprocess
import tempfile


ROOT = Path(__file__).resolve().parent
STAGES = ("vert", "edge", "weights", "blend", "easu", "rcas", "sgsr")


def notice(path):
    return "/*\n" + "\n".join(" * " + line for line in path.read_text().splitlines()) + "\n */\n"


def array(name, values, ctype, width, columns):
    rows = [f"static const {ctype} {name}[] = {{"]
    for start in range(0, len(values), columns):
        rows.append("    " + ", ".join(f"0x{v:0{width}x}" for v in values[start:start + columns]) + ",")
    rows.append("};\n")
    return "\n".join(rows)


def lut_bytes(path, symbol, expected_size):
    source = path.read_text()
    match = re.search(r"\b" + symbol + r"\[\]\s*=\s*\{(.*?)\};", source, re.S)
    if not match:
        raise ValueError(f"Missing upstream LUT initializer: {path}:{symbol}")
    values = [int(value, 16) for value in re.findall(r"0x([0-9a-fA-F]{2})\b", match[1])]
    if len(values) != expected_size:
        raise ValueError(f"Unexpected LUT size for {symbol}: {len(values)}, expected {expected_size}")
    return values


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--compiler", help="Path to glslc (preferred) or glslangValidator")
    parser.add_argument("--scratch", type=Path, help="Parent directory for temporary SPIR-V files")
    args = parser.parse_args()
    compiler = args.compiler or shutil.which("glslc") or shutil.which("glslangValidator")
    if not compiler:
        parser.error("glslc/glslangValidator not found; supply --compiler")
    compiler = str(Path(compiler).resolve())
    glslang = "glslang" in Path(compiler).name.lower()
    if args.scratch:
        args.scratch.mkdir(parents=True, exist_ok=True)

    smaa_notice = notice(ROOT / "smaa/LICENSE.txt")
    fsr_notice = notice(ROOT / "fsr/LICENSE.txt")
    sgsr_notice = notice(ROOT / "sgsr/LICENSE")
    spv = ["/* Generated by post/generate.py. Do not edit.\n"
           " * GLSL entry points target Vulkan 1.3; no shader compiler is used on device.\n"
           " * SMAA, FidelityFX FSR 1.0.2, and Snapdragon GSR 1 licenses follow.\n */\n",
           smaa_notice, fsr_notice, sgsr_notice, "#pragma once\n#include <stdint.h>\n\n"]
    with tempfile.TemporaryDirectory(prefix="post-shaders-", dir=args.scratch) as work:
        for stage in STAGES:
            source = ROOT / ("post.vert" if stage == "vert" else f"post_{stage}.frag")
            output = Path(work) / f"{stage}.spv"
            if glslang:
                command = [compiler, "-V", "--target-env", "vulkan1.3", str(source), "-o", str(output)]
            else:
                command = [compiler, "--target-env=vulkan1.3", "-O", str(source), "-o", str(output)]
            subprocess.run(command, check=True)
            data = output.read_bytes()
            if len(data) % 4:
                raise ValueError(f"SPIR-V output is not word aligned: {stage}")
            words = struct.unpack(f"<{len(data) // 4}I", data)
            spv.append(array(f"post_{stage}_spv", words, "uint32_t", 8, 8))
            print(f"post_{stage}_spv: {len(data)} bytes")

    area = lut_bytes(ROOT / "smaa/AreaTex.h", "areaTexBytes", 160 * 560 * 2)
    search = lut_bytes(ROOT / "smaa/SearchTex.h", "searchTexBytes", 64 * 16)
    lut = ["/* Generated by post/generate.py from the original iryoku/smaa LUTs.\n"
           " * Upload tightly packed: area 160x560 R8G8_UNORM; search 64x16 R8_UNORM.\n"
           " * Preserve byte order and row order; sample both with linear clamp.\n */\n",
           smaa_notice, "#pragma once\n#include <stdint.h>\n\n",
           array("post_area_bytes", area, "uint8_t", 2, 16),
           array("post_search_bytes", search, "uint8_t", 2, 16)]
    # Do not replace either checked-in header until every shader has compiled.
    (ROOT.parent / "vk_post_spv.h").write_text("".join(spv))
    (ROOT.parent / "vk_post_lut.h").write_text("".join(lut))
    print(f"post_area_bytes: {len(area)} bytes; post_search_bytes: {len(search)} bytes")


if __name__ == "__main__":
    main()
