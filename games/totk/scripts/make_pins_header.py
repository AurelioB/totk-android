#!/usr/bin/env python3
"""The pinned 1.4.3 hashes and sizes (assets/expected-v1.4.3.json) as C macros for the on-device setup library and the
runtime: totk_pins.h. Only hashes, sizes and ids; nothing derived from game bytes beyond those digests.
usage: make_pins_header.py assets/expected-v1.4.3.json <out>/totk_pins.h"""
import json,re,sys
from pathlib import Path
if len(sys.argv)!=3:sys.exit(__doc__)
pins=json.loads(Path(sys.argv[1]).read_text());out=Path(sys.argv[2])
def sha(v,what):
    if not re.fullmatch(r'[0-9a-f]{64}',v):sys.exit(f'{what}: not a lowercase SHA-256')
    return v
assert re.fullmatch(r'[0-9A-F]{16}',pins['title_id']) and isinstance(pins['version'],int)
rows=[('TITLE_ID',f'"{pins["title_id"]}"'),('VERSION',str(pins['version'])),('DISPLAY_VERSION',f'"{pins["display_version"]}"')]
for name in ('main','sdk','subsdk0','main.npdm','rtld'):
    rows.append(('EXEFS_SHA256_'+name.replace('.','_').upper(),f'"{sha(pins["exefs_sha256"][name],name)}"'))
for name in ('main','sdk','subsdk0'):
    rows.append(('ANDROID_REWRITTEN_SHA256_'+name.upper(),f'"{sha(pins["android_rewritten_sha256"][name+".patched.bin"],name)}"'))
# Added by the rewriter port once its reference tables writer exists; consumers test #ifdef.
if 'android_runtime_tables_sha256' in pins:
    rows.append(('ANDROID_RUNTIME_TABLES_SHA256',f'"{sha(pins["android_runtime_tables_sha256"],"runtime tables")}"'))
size=pins['romfs']['size'];assert isinstance(size,int) and size>0
rows+=[('ROMFS_SIZE',f'{size}ULL'),('ROMFS_SHA256',f'"{sha(pins["romfs"]["sha256"],"romfs")}"'),
       ('ROMFS_INDEX_SHA256',f'"{sha(pins["romfs_index_sha256"],"romfs index")}"')]
text=('/* Generated by scripts/make_pins_header.py from '+Path(sys.argv[1]).name+'; do not edit. */\n#ifndef TOTK_PINS_H\n#define TOTK_PINS_H\n'
      +''.join(f'#define TOTK_PIN_{k} {v}\n' for k,v in rows)+'#endif\n')
# Rewrite only on change so make does not rebuild everything that includes it.
if not out.exists() or out.read_text()!=text:
    out.parent.mkdir(parents=True,exist_ok=True);tmp=out.with_name(out.name+'.tmp');tmp.write_text(text);tmp.replace(out)
